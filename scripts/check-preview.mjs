import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';
const path=process.argv[2];
if(!path)throw new Error('Pass the absolute path to the standalone preview HTML.');
const html=readFileSync(path,'utf8');
const scripts=[...html.matchAll(/<script(?: type="module")?>([\s\S]*?)<\/script>/g)].map(m=>m[1]);
assert.equal(scripts.length,2);
const errors=[];
const virtualConsole=new VirtualConsole();
virtualConsole.on('jsdomError',e=>errors.push(e.message));
const dom=new JSDOM(html,{url:'file:///preview/Dadinkowa-Preview.html',runScripts:'outside-only',virtualConsole});
dom.window.scrollTo=()=>{};
dom.window.IntersectionObserver=class{observe(){} unobserve(){} disconnect(){}};
for(const script of scripts)dom.window.eval(script);
const wait=()=>new Promise(resolve=>setTimeout(resolve,50));
await wait();
const doc=dom.window.document;
assert.match(doc.querySelector('h1').textContent,/Considered style/);
assert.match(doc.querySelector('.brand img').src,/^data:image\/png;base64,/);
assert.match(doc.querySelector('.hero-slide img').src,/^data:image\/svg\+xml;base64,/);
const collections=[...doc.querySelectorAll('.desktop-nav a')].find(a=>a.textContent==='Collections');
assert.equal(collections.getAttribute('href'),'#/lookbook');
collections.click();
await wait();
assert.match(doc.querySelector('h1').textContent,/Cloth. Form/);
assert.equal(doc.querySelectorAll('.look-card').length,5);
[...doc.querySelectorAll('.filters button')].find(b=>b.textContent==='Fabrics').click();
await wait();
assert.equal(doc.querySelectorAll('.look-card').length,1);
assert.match(doc.querySelector('.look-card img').src,/^data:image\/svg\+xml;base64,/);
const contact=[...doc.querySelectorAll('.desktop-nav a')].find(a=>a.textContent==='Contact');contact.click();
await wait();
assert.match(doc.querySelector('h1').textContent,/Good style starts/);
assert.ok(doc.querySelector('textarea'));
assert.deepEqual(errors,[]);
console.log('PASS: standalone production bundle boots offline; all 3 hash routes, embedded logo/art and category filtering work in jsdom. No simulated runtime errors.');
dom.window.close();
